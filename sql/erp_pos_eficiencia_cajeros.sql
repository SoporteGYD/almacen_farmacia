-- Módulo de eficiencia POS G&D (MariaDB 10.4+, MySQL 8+)
-- Solo crea una tabla de telemetría. No altera ventas ni existencias.
-- Ejecutar en la base de PRUEBAS `prueba`, una única vez o de nuevo de forma idempotente.
CREATE TABLE IF NOT EXISTS erp_pos_eficiencia_cajeros (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  usuario_id INT NOT NULL,
  sucursal_id INT NOT NULL,
  caja_id INT NOT NULL,
  turno_id BIGINT UNSIGNED NOT NULL,
  venta_id BIGINT UNSIGNED NULL,
  estado ENUM('INICIADA','COMPLETADA') NOT NULL DEFAULT 'INICIADA',
  inicio_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  final_en DATETIME(6) NULL,
  total_seg INT UNSIGNED NULL,
  captura_seg INT UNSIGNED NULL,
  pago_seg INT UNSIGNED NULL,
  cobro_red_seg INT UNSIGNED NULL,
  inactivo_seg INT UNSIGNED NULL,
  oculto_seg INT UNSIGNED NULL,
  activo_seg INT UNSIGNED NULL,
  gestion_almacen_seg INT UNSIGNED NULL,
  lineas INT UNSIGNED NOT NULL DEFAULT 0,
  piezas INT UNSIGNED NOT NULL DEFAULT 0,
  busquedas INT UNSIGNED NOT NULL DEFAULT 0,
  seleccion_catalogo INT UNSIGNED NOT NULL DEFAULT 0,
  escaneos INT UNSIGNED NOT NULL DEFAULT 0,
  selecciones_buscador INT UNSIGNED NOT NULL DEFAULT 0,
  cambios_cantidad INT UNSIGNED NOT NULL DEFAULT 0,
  productos_quitados INT UNSIGNED NOT NULL DEFAULT 0,
  intentos_cobro INT UNSIGNED NOT NULL DEFAULT 0,
  errores_cobro INT UNSIGNED NOT NULL DEFAULT 0,
  solicitudes_almacen INT UNSIGNED NOT NULL DEFAULT 0,
  metodo_pago VARCHAR(20) NULL,
  actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_eficiencia_token (token),
  UNIQUE KEY uq_eficiencia_venta (venta_id),
  KEY idx_eficiencia_periodo (inicio_en,estado),
  KEY idx_eficiencia_cajero (usuario_id,inicio_en),
  KEY idx_eficiencia_sucursal (sucursal_id,inicio_en)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
